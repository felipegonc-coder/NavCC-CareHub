// @ts-check
// THIRD_PARTY_NOTICES.md: every shipped package with its version, license, repository and the
// text of its LICENSE and NOTICE files. No dates, so the file changes only when packages change.
import fs from 'node:fs';
import path from 'node:path';
import { compareText } from './inventory.mjs';
import { isRecord } from './policy.mjs';

/** @typedef {{ name: string, version: string, license: string, repository: string | null, files: { file: string, text: string }[] }} NoticeEntry */

/**
 * A browsable URL for the `repository` field of a package.json, or null.
 *
 * @param {unknown} repository "user/repo", "github:user/repo", a git URL, or `{ url }`.
 * @returns {string | null}
 */
export function repositoryUrl(repository) {
  const raw = isRecord(repository) ? repository.url : repository;
  if (typeof raw !== 'string' || raw.trim() === '') return null;
  const shorthand = /^(?:(github|gitlab|bitbucket):)?([\w.-]+\/[\w.-]+)$/.exec(raw.trim());
  const hosts = { github: 'github.com', gitlab: 'gitlab.com', bitbucket: 'bitbucket.org' };
  const url = shorthand
    ? `https://${hosts[/** @type {keyof typeof hosts} */ (shorthand[1] ?? 'github')]}/${shorthand[2]}`
    : raw
        .trim()
        .replace(/^git\+/, '')
        .replace(/^(?:git|ssh):\/\/(?:[^@/]+@)?/, 'https://')
        .replace(/^[^@/:]+@([^:/]+):/, 'https://$1/');
  return url.replace(/\.git$/, '').replace(/\/+$/, '');
}

/**
 * LICENSE, LICENCE, COPYING and NOTICE files at the top of a package (not code), licenses first.
 *
 * @param {string} dir
 * @returns {{ file: string, text: string }[]}
 */
export function licenseFiles(dir) {
  const rank = (/** @type {string} */ file) => (/^notice/i.test(file) ? 1 : 0);
  return fs
    .readdirSync(dir)
    .filter(
      (file) =>
        /^(?:licen[cs]e|copying|notice)(?:[.\-_].*)?$/i.test(file) &&
        !/\.(?:[cm]?[jt]sx?|json|map)$/i.test(file),
    )
    .filter((file) => fs.statSync(path.join(dir, file), { throwIfNoEntry: false })?.isFile())
    .sort((a, b) => rank(a) - rank(b) || compareText(a.toLowerCase(), b.toLowerCase()))
    .map((file) => ({ file, text: fs.readFileSync(path.join(dir, file), 'utf8') }))
    .filter(({ text }) => !text.includes('\u0000'))
    .map(({ file, text }) => ({
      file,
      text: text
        .replace(/^\uFEFF/, '')
        .replace(/\r\n?/g, '\n')
        .replace(/[ \t]+$/gm, '')
        .trim(),
    }))
    .filter(({ text }) => text !== '');
}

/**
 * @param {NoticeEntry[]} entries
 * @returns {string} Markdown, sorted by name and version.
 */
export function renderNotices(entries) {
  const sorted = [...entries].sort(
    (a, b) => compareText(a.name, b.name) || compareText(a.version, b.version),
  );
  const lines = [
    '# Third-party notices',
    '',
    'Care Hub includes the open-source packages below, each with its version, license,',
    'repository and license text. Generated by `node scripts/license-check.mjs --notices`',
    'and regenerated by CI on `main`. Do not edit by hand.',
    '',
    `Packages: ${sorted.length}`,
  ];
  for (const { name, version, license, repository, files } of sorted) {
    lines.push(
      '',
      `## ${name} ${version}`,
      '',
      `- License: ${license}`,
      `- Repository: ${repository ?? 'not listed'}`,
    );
    if (files.length === 0) lines.push('', '_No license or notice file in the package._');
    for (const { file, text } of files) {
      const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((match) => match[0].length));
      const fence = '`'.repeat(longest + 1);
      lines.push('', `### ${file}`, '', `${fence}text`, text, fence);
    }
  }
  return `${lines.join('\n')}\n`;
}
